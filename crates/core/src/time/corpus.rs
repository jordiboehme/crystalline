//! The frozen date corpus: every row of the J2 table, the J3 forms, the
//! kept-file stamps, the RFC 2822 inputs, the differential test's seeds
//! and the serde adapters' inputs, each with what every parser makes of
//! it, as literal strings.
//!
//! Written while chrono was still in the build: a differential test held
//! every row against chrono, with only the differences a ruling allows
//! (J4: a leap second read as `:59`, a year outside 0000 to 9999 refused),
//! so each row's strings are chrono's answer. chrono has left the build
//! since; `time::tests::corpus_holds` keeps the parsers and the bytes the
//! serde adapters write to these rows, and `time::tests::print_corpus`
//! prints them again.

/// What each parser makes of one input: the RFC 3339 bytes (`%Y-%m-%d`
/// for a date) of the value it read, or `None` when it refuses the input.
#[derive(Debug, PartialEq)]
pub struct Expect {
    /// `parse_rfc3339`, then `OffsetStamp::rfc3339`.
    pub rfc3339: Option<&'static str>,
    /// `parse_lenient_offset` (and the serde adapters), then
    /// `OffsetStamp::rfc3339`.
    pub lenient: Option<&'static str>,
    /// `parse_date`, then `Day::ymd`.
    pub date: Option<&'static str>,
    /// `parse_lenient_date` (and the `day` adapter), then `Day::ymd`.
    pub lenient_date: Option<&'static str>,
    /// `parse_kept_stamp`, then `Stamp::rfc3339`.
    pub kept: Option<&'static str>,
    /// `parse_rfc2822`, then `OffsetStamp::rfc3339`.
    pub rfc2822: Option<&'static str>,
    /// What the `stamp` serde adapter writes for the value it read (the
    /// `lenient` value in UTC): `Z` and the fraction in groups of none, 3,
    /// 6 or 9 digits.
    pub stamp_serde: Option<&'static str>,
    /// What the `offset_stamp` serde adapter writes for the value it read
    /// (the `lenient` value): `Z` for offset zero, else `+hh:mm`.
    pub offset_stamp_serde: Option<&'static str>,
}

