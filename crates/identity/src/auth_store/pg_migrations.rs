//! The auth tables on Postgres: their own migration set with its own ledger,
//! `auth_schema_migration`, applied through the index's
//! [`crystalline_index::postgres::apply_locked_set`] under the shared
//! migration lock.
//!
//! v1 is the Turso `SCHEMA` of `auth_store.rs`, columns added by
//! `ensure_column` included, in Postgres types: `INTEGER` is `BIGINT`, an
//! `AUTOINCREMENT` key is an identity column, and every text column is
//! `COLLATE "C"`, so ordering and comparison are bytewise like SQLite's
//! `BINARY`, whatever the database's default collation is. The token columns
//! of `oauth_grants` stay, holding placeholders, because the shared SQL
//! writes them.

use crystalline_index::postgres::{Migration, MigrationSet};

/// The auth tables' migration set, ledger `auth_schema_migration`.
pub const AUTH_MIGRATIONS: MigrationSet = MigrationSet {
    ledger: "auth_schema_migration",
    steps: AUTH_STEPS,
    index_backfill: false,
};

/// The steps of [`AUTH_MIGRATIONS`], ascending. Append-only.
const AUTH_STEPS: &[Migration] = &[Migration {
    version: 1,
    label: "auth tables",
    sql: AUTH_V1,
}];

/// The tables [`AUTH_MIGRATIONS`] creates, its ledger left out. They share
/// the database and schema with the index, so none of them may share a name
/// with an index or instance table, and a wipe must leave all of them alone
/// (`auth_index_instance_tables_disjoint_and_not_wiped`).
pub const AUTH_TABLES: &[&str] = &[
    "users",
    "sessions",
    "mcp_tokens",
    "domain_acl",
    "domain_member",
    "identity_link",
    "github_link",
    "oauth_clients",
    "oauth_grants",
    "oauth_grant_token",
    "oauth_grant_ended",
    "overlay_grant",
    "account_write_domain",
    "domain_reflection_grant",
    "github_delivery",
];

const AUTH_V1: &str = r#"
CREATE TABLE IF NOT EXISTS users (
    name TEXT COLLATE "C" PRIMARY KEY,
    display TEXT COLLATE "C" NOT NULL,
    email TEXT COLLATE "C",
    role TEXT COLLATE "C" NOT NULL,
    reflection TEXT COLLATE "C",
    pass_hash TEXT COLLATE "C",
    disabled BIGINT NOT NULL DEFAULT 0,
    last_seen_at TEXT COLLATE "C",
    created_at TEXT COLLATE "C" NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT COLLATE "C" PRIMARY KEY,
    user_name TEXT COLLATE "C" NOT NULL,
    csrf TEXT COLLATE "C" NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_name ON sessions (user_name);
CREATE INDEX IF NOT EXISTS sessions_expires_at ON sessions (expires_at);
CREATE TABLE IF NOT EXISTS mcp_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user" TEXT COLLATE "C" NOT NULL,
    token_hash TEXT COLLATE "C" NOT NULL UNIQUE,
    label TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    last_used TEXT COLLATE "C"
);
CREATE INDEX IF NOT EXISTS mcp_tokens_user ON mcp_tokens ("user");
CREATE TABLE IF NOT EXISTS domain_acl (
    domain TEXT COLLATE "C" PRIMARY KEY NOT NULL,
    visibility TEXT COLLATE "C" NOT NULL,
    owner TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL
);
CREATE TABLE IF NOT EXISTS domain_member (
    domain TEXT COLLATE "C" NOT NULL,
    principal_kind TEXT COLLATE "C" NOT NULL DEFAULT 'user',
    principal TEXT COLLATE "C" NOT NULL,
    level TEXT COLLATE "C" NOT NULL,
    reflection TEXT COLLATE "C",
    added_by TEXT COLLATE "C" NOT NULL,
    added_at TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (domain, principal_kind, principal)
);
CREATE INDEX IF NOT EXISTS domain_member_principal
    ON domain_member (principal_kind, principal);
CREATE TABLE IF NOT EXISTS identity_link (
    issuer TEXT COLLATE "C" NOT NULL,
    subject TEXT COLLATE "C" NOT NULL,
    "user" TEXT COLLATE "C" NOT NULL,
    linked_at TEXT COLLATE "C" NOT NULL,
    linked_by TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (issuer, subject)
);
CREATE INDEX IF NOT EXISTS identity_link_user ON identity_link ("user");
CREATE UNIQUE INDEX IF NOT EXISTS identity_link_issuer_user
    ON identity_link (issuer, "user");
CREATE TABLE IF NOT EXISTS github_link (
    account TEXT COLLATE "C" PRIMARY KEY NOT NULL,
    host TEXT COLLATE "C" NOT NULL,
    github_id BIGINT NOT NULL,
    login TEXT COLLATE "C" NOT NULL,
    linked_at TEXT COLLATE "C" NOT NULL,
    token_live BIGINT NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS github_link_host_id ON github_link (host, github_id);
CREATE TABLE IF NOT EXISTS oauth_clients (
    client_id TEXT COLLATE "C" PRIMARY KEY,
    client_name TEXT COLLATE "C" NOT NULL,
    client_uri TEXT COLLATE "C",
    redirect_uris TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    last_used TEXT COLLATE "C"
);
CREATE TABLE IF NOT EXISTS oauth_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user" TEXT COLLATE "C" NOT NULL,
    client_id TEXT COLLATE "C" NOT NULL,
    resource TEXT COLLATE "C" NOT NULL,
    access_hash TEXT COLLATE "C" NOT NULL UNIQUE,
    access_expires_at BIGINT NOT NULL,
    refresh_hash TEXT COLLATE "C" NOT NULL UNIQUE,
    previous_refresh_hash TEXT COLLATE "C",
    refresh_expires_at BIGINT NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    last_used TEXT COLLATE "C"
);
CREATE INDEX IF NOT EXISTS oauth_grants_user ON oauth_grants ("user");
CREATE INDEX IF NOT EXISTS oauth_grants_client ON oauth_grants (client_id);
CREATE INDEX IF NOT EXISTS oauth_grants_previous_refresh
    ON oauth_grants (previous_refresh_hash);
CREATE TABLE IF NOT EXISTS oauth_grant_token (
    refresh_hash TEXT COLLATE "C" PRIMARY KEY,
    grant_id BIGINT NOT NULL,
    access_hash TEXT COLLATE "C" UNIQUE,
    access_expires_at BIGINT NOT NULL,
    refresh_expires_at BIGINT NOT NULL,
    issued_at BIGINT NOT NULL,
    rotated_at BIGINT,
    rotated_from TEXT COLLATE "C"
);
CREATE INDEX IF NOT EXISTS oauth_grant_token_grant ON oauth_grant_token (grant_id);
CREATE INDEX IF NOT EXISTS oauth_grant_token_from ON oauth_grant_token (rotated_from);
CREATE TABLE IF NOT EXISTS oauth_grant_ended (
    grant_id BIGINT PRIMARY KEY,
    "user" TEXT COLLATE "C" NOT NULL,
    client_id TEXT COLLATE "C" NOT NULL,
    client_name TEXT COLLATE "C" NOT NULL,
    redirect_host TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    last_used TEXT COLLATE "C",
    ended_at BIGINT NOT NULL,
    reason TEXT COLLATE "C" NOT NULL
);
CREATE INDEX IF NOT EXISTS oauth_grant_ended_user ON oauth_grant_ended ("user", ended_at);
CREATE TABLE IF NOT EXISTS overlay_grant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain TEXT COLLATE "C" NOT NULL,
    path TEXT COLLATE "C" NOT NULL,
    owner TEXT COLLATE "C" NOT NULL,
    grantee TEXT COLLATE "C",
    token_hash TEXT COLLATE "C" NOT NULL UNIQUE,
    created_at TEXT COLLATE "C" NOT NULL,
    expires_at TEXT COLLATE "C",
    revoked_at TEXT COLLATE "C"
);
CREATE INDEX IF NOT EXISTS overlay_grant_draft
    ON overlay_grant (domain, owner, path);
CREATE INDEX IF NOT EXISTS overlay_grant_grantee
    ON overlay_grant (grantee, domain, path);
CREATE TABLE IF NOT EXISTS account_write_domain (
    account TEXT COLLATE "C" NOT NULL,
    pattern TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (account, pattern)
);
CREATE TABLE IF NOT EXISTS domain_reflection_grant (
    domain TEXT COLLATE "C" NOT NULL,
    account TEXT COLLATE "C" NOT NULL,
    level TEXT COLLATE "C" NOT NULL,
    added_by TEXT COLLATE "C" NOT NULL,
    added_at TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (domain, account)
);
CREATE TABLE IF NOT EXISTS github_delivery (
    id TEXT COLLATE "C" PRIMARY KEY,
    received_at BIGINT NOT NULL
);
"#;
